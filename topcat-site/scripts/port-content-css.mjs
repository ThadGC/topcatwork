#!/usr/bin/env node
/**
 * Regenerate src/styles/content.css from services/service.css.
 *
 * content.css is a VERBATIM port with exactly one range removed, so it should
 * never be hand-edited — re-run this instead, and the diff will show you
 * precisely what changed in the source.
 *
 * Two traps this script exists to avoid:
 *
 *   1. services/service.css has 387 lines and NO trailing newline. Slicing it
 *      with `sed -n '98,386p'` silently drops the final rule
 *      (`.legal .legal-close`) and leaves the file with an unclosed block.
 *      Because CSS nesting is valid now, PostCSS does not always complain —
 *      it folds whatever comes next INTO that rule, and you get a stylesheet
 *      that parses and is wrong.
 *   2. The excised range is identified by line number, which is only safe if
 *      the boundaries are checked. They are, below, against the exact text of
 *      the first and last line of the block.
 *
 * Usage:  node scripts/port-content-css.mjs [--check]
 *
 * `--check` regenerates into memory and exits non-zero if the file on disk
 * differs — for CI, or for anyone who suspects a hand-edit.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const WEB = resolve(HERE, '..');
const REPO = resolve(WEB, '..');

const SOURCE = join(REPO, 'services', 'service.css');
const TARGET = join(WEB, 'src', 'styles', 'content.css');

/**
 * The chrome block, 1-indexed and inclusive. It moves to
 * components/chrome/chrome.css, which ports site.css's richer reading of the
 * same elements and re-states every service.css divergence in its §12.
 */
const EXCISE = { from: 43, to: 97 };

/** Guards against a source edit shifting the block out from under us. */
const EXPECT_FIRST = 'header.bar{';
const EXPECT_LAST = '@media(max-width:1120px){header.bar .bar-cta{display:none}}';

const BANNER = `/* ==========================================================================
   content.css  —  services/service.css, VERBATIM but for one excised block
   --------------------------------------------------------------------------
   The Family-B ("SEO shell") stylesheet. 172 of the 178 legacy pages link it
   as \`/services/service.css\`. Every line below is byte-for-byte from that
   file, in its source order, with ONE range removed:

     lines ${EXCISE.from}-${EXCISE.to}  header.bar / .brand / nav.top / .bar-cta and their media
                  queries -> components/chrome/chrome.css, which ports
                  site.css's richer reading of the same chrome and re-states
                  each place service.css disagrees in its §12.

   GENERATED by scripts/port-content-css.mjs. Do not hand-edit; re-run it.
   (Line endings are normalised CRLF -> LF; nothing else is touched.)
   \`node scripts/port-content-css.mjs --check\` fails if this file has drifted.

   ---------------------------------------------------------------------------
   WHY THE :root AND body BLOCKS ARE KEPT, NOT DEDUPED AGAINST globals.css
   ---------------------------------------------------------------------------
   globals.css §4 already expresses the content-page token root, but it does so
   as \`[data-tokens='content']\` — an attribute on <body> that a nested layout
   cannot set, because <body> belongs to the root layout.

   This file does not need the attribute. It is imported by
   app/stones/layout.tsx, so Next only serves it on the routes that are
   supposed to have it, and its plain \`:root\` and \`body\` selectors are simply
   correct there. Keeping them means the three token divergences (--muted 0.60,
   --faint 0.34, the 0.80px --uipx floor), \`body{font-weight:300;line-height:
   1.6;padding-top:var(--barH)}\` and \`body::before{z-index:-1}\` are all live
   from the first paint, with no JavaScript in the path and no flash of the
   home page's token root.

   The \`data-tokens\` attribute is still set (see app/stones/layout.tsx) because
   chrome.css §12 keys off it, but nothing that affects layout depends on that
   script running.

   Cascade order is load-bearing and matches the legacy <link> order:
     globals.css -> chrome.css -> content.css -> stone.css
   stone.css re-declares \`body::before\` at z-index:0 and must come last.
   ========================================================================== */

`;

function build() {
  // service.css is CRLF. Normalise to LF first: everything else in web/ is LF,
  // and a stray \r on the end of every line makes `--check` fail on one
  // machine and pass on another. CSS is insensitive to it, so the port stays
  // verbatim in every way that renders.
  const lines = readFileSync(SOURCE, 'utf8').replace(/\r\n/g, '\n').split('\n');

  const first = lines[EXCISE.from - 1];
  const last = lines[EXCISE.to - 1];
  if (first !== EXPECT_FIRST || last !== EXPECT_LAST) {
    throw new Error(
      `service.css has shifted: expected lines ${EXCISE.from}/${EXCISE.to} to be\n` +
        `  ${EXPECT_FIRST}\n  ${EXPECT_LAST}\nbut found\n  ${first}\n  ${last}\n` +
        'Re-locate the chrome block and update EXCISE before regenerating.',
    );
  }

  const head = lines.slice(0, EXCISE.from - 1);
  const tail = lines.slice(EXCISE.to); // to end, trailing newline or not
  const css = `${BANNER}${head.join('\n')}\n\n${tail.join('\n')}\n`;

  // A stylesheet that does not balance is a stylesheet that swallowed a rule.
  const open = (css.match(/\{/g) ?? []).length;
  const close = (css.match(/\}/g) ?? []).length;
  if (open !== close) {
    throw new Error(`unbalanced braces: ${open} open, ${close} close`);
  }
  return css;
}

const css = build();

if (process.argv.includes('--check')) {
  const onDisk = readFileSync(TARGET, 'utf8');
  if (onDisk !== css) {
    console.error(
      'content.css has drifted from services/service.css.\n' +
        'Run `node scripts/port-content-css.mjs` and review the diff.',
    );
    process.exit(1);
  }
  console.log('content.css matches services/service.css.');
} else {
  writeFileSync(TARGET, css);
  console.log(
    `content.css regenerated — ${css.split('\n').length} lines, ` +
      `service.css lines ${EXCISE.from}-${EXCISE.to} excised.`,
  );
}
