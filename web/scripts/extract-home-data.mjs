/**
 * extract-home-data.mjs
 *
 * Lifts the home page's content arrays out of `assets/site.js` into typed
 * modules under `src/data/home/`.
 *
 * The legacy home page has no CMS: the copy for the services strip, the four
 * process steps, the reviews, the projects and the FAQ is hard-coded as object
 * literals near the top of site.js. Retyping ~9 kB of client copy by hand is
 * how a port loses an apostrophe, so this script slices the literal out of the
 * source and evaluates it, then serialises the result. The text that lands in
 * src/data/home/*.ts is therefore the client's text, character for character.
 *
 * Two source quirks are preserved rather than tidied:
 *   - PROCESS entries declare `d:` twice. Later key wins in JS, so the second
 *     ("Understanding your space and style.") is what the browser has always
 *     used. Evaluating instead of transcribing keeps that automatic.
 *   - REVIEWS ends with `.filter(...).map(...)`. The filter drops four named
 *     reviewers; the map adds `a` and a placeholder image. The filter is
 *     applied here so the count in the data file is the count that renders.
 *
 * Run: pnpm run extract:home-data
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = resolve(HERE, '../../assets/site.js');
const OUT_DIR = resolve(HERE, '../src/data/home');

const js = readFileSync(SRC, 'utf8');

/**
 * Slice the literal that follows `const <name> =`, balancing brackets while
 * skipping strings, template literals, comments and regex-ish escapes.
 */
function literalOf(name) {
  const decl = new RegExp(`(?:^|\\n)\\s*(?:const|var|let)\\s+${name}\\s*=\\s*`, 'm');
  const m = decl.exec(js);
  if (!m) throw new Error(`no declaration for ${name}`);
  let i = m.index + m[0].length;
  const open = js[i];
  const close = open === '[' ? ']' : '}';
  if (open !== '[' && open !== '{') throw new Error(`${name} is not an array/object literal`);
  let depth = 0;
  let str = null;
  for (; i < js.length; i++) {
    const c = js[i];
    if (str) {
      if (c === '\\') i++;
      else if (c === str) str = null;
      continue;
    }
    if (c === '"' || c === "'" || c === '`') str = c;
    else if (c === '/' && js[i + 1] === '/') i = js.indexOf('\n', i);
    else if (c === '/' && js[i + 1] === '*') i = js.indexOf('*/', i) + 1;
    else if (c === open) depth++;
    else if (c === close) {
      depth--;
      if (depth === 0) return js.slice(m.index + m[0].length, i + 1);
    }
  }
  throw new Error(`unbalanced literal for ${name}`);
}

const evalLiteral = (name) => new Function(`return (${literalOf(name)});`)();

/* --------------------------------------------------------------- extract */

const SS = evalLiteral('SS');
const SERVICES = evalLiteral('SERVICES');
const PROCESS = evalLiteral('PROCESS');
const PROC_COPY = evalLiteral('PROC_COPY');
const PROC_DETAIL = evalLiteral('PROC_DETAIL');
const PROJECTS = evalLiteral('PROJECTS');
const FAQS = evalLiteral('FAQS');

// site.js:1459 — the four names the client asked to be withheld.
const REVIEW_DROP = /luke|copley|thadeus|tabrez/i;
const REVIEWS = evalLiteral('REVIEWS').filter((r) => !REVIEW_DROP.test(r.n));

/* ------------------------------------------------------------------ emit */

mkdirSync(OUT_DIR, { recursive: true });

const lit = (v) => JSON.stringify(v, null, 2).replace(/\n/g, '\n');

function write(file, header, body) {
  writeFileSync(resolve(OUT_DIR, file), `${header}\n${body}\n`, 'utf8');
  console.log(`  ${file}`);
}

const GEN = (src) =>
  `/* GENERATED by scripts/extract-home-data.mjs from ${src}. Do not hand-edit. */`;

write(
  'srcset.ts',
  `${GEN('assets/site.js — the SS map')}

/**
 * The legacy responsive-image table. site.js builds every card's \`srcset\`
 * through \`ss(url, sizes)\` (site.js:112), which looks the *display* URL up in
 * this map and emits nothing when there is no entry — a plain \`src\` with no
 * srcset at all. \`srcSet()\` below reproduces that exactly, including the
 * "no entry, no attribute" case, because a srcset invented for a URL the map
 * does not list would point at files that are not on the server.
 */`,
  `export const SRCSET: Readonly<Record<string, string>> = ${lit(SS)};

/**
 * site.js:112 — \`function ss(u,z)\`. Returns props, not an attribute string.
 *
 * THE LEADING SLASH. Three of the map's keys are relative — \`assets/team/
 * fitting.jpg\` and its two siblings — because that is the form site.js wrote
 * into its own markup. The port serves everything from the root, so its callers
 * pass \`/assets/team/fitting.jpg\`, which missed the map and dropped the
 * srcset: About's collage tile fetched the 81,685-byte source JPEG instead of
 * the 17,276-byte \`team-fitting-386.webp\` that exists for exactly that slot
 * (measured 105x145 CSS, 394 device px at dpr 3.75 — 386w is the right rung).
 *
 * Both forms are tried rather than rewriting the keys, so the map stays a
 * verbatim copy of \`SS\` and a caller may pass either shape.
 */
export function srcSet(
  url: string | undefined,
  sizes: string,
): { srcSet: string; sizes: string } | Record<string, never> {
  const s = url
    ? (SRCSET[url] ?? (url.startsWith('/') ? SRCSET[url.slice(1)] : SRCSET['/' + url]))
    : undefined;
  return s ? { srcSet: s, sizes } : {};
}`,
);

write(
  'services.ts',
  `${GEN('assets/site.js:113 — SERVICES')}

/**
 * The eight cards in the services strip, in source order. \`long\` is the copy
 * on the back of the flip card; the front shows only the title, because the
 * home page calls buildCards with \`nameOnly\` (site.js) and so never renders
 * the \`d\` field that other pages use.
 */`,
  `export interface Service {
  /** Card title, also the flip-card's accessible name. */
  t: string;
  /** Back-of-card paragraph. */
  long: string;
  /** Legacy .html leaf under /services/. */
  href: string;
  /** Display URL; look it up in SRCSET for the responsive set. */
  img: string;
}

export const SERVICES: readonly Service[] = ${lit(SERVICES)};`,
);

write(
  'process.ts',
  `${GEN('assets/site.js:179 — PROCESS, PROC_COPY, PROC_DETAIL')}

/**
 * The four process steps, plus the copy that actually renders.
 *
 * PROCESS[n].d appears TWICE in the source object literal. The later key wins
 * in JS, so \`d\` here is the second string — matching what the legacy page has
 * always shown. The flow tiles do not read \`d\` at all; they read PROC_COPY,
 * which is a separate, shorter line per step. PROC_DETAIL is the modal body.
 */`,
  `export interface ProcessStep {
  t: string;
  img: string;
  /** The second \`d:\` in the source literal — the one JS keeps. */
  d: string;
  long: string;
}

export interface ProcessDetail {
  lede: string;
  /** [heading, body] pairs. */
  points: readonly (readonly [string, string])[];
}

export const PROCESS: readonly ProcessStep[] = ${lit(PROCESS)};

/** site.js:193 — the one-liner under each tile's heading. */
export const PROC_COPY: readonly string[] = ${lit(PROC_COPY)};

/** site.js:243 — the "Read more" modal for each step. */
export const PROC_DETAIL: readonly ProcessDetail[] = ${lit(PROC_DETAIL)};`,
);

write(
  'reviews.ts',
  `${GEN('assets/site.js:1443 — REVIEWS')}

/**
 * Google reviews, verbatim, including the emoji and the curly quotes.
 *
 * The source array ends with \`.filter(r => !/luke|copley|thadeus|tabrez/i
 * .test(r.n))\` — four reviewers the client asked to be withheld. That filter
 * is applied at extraction time, so this array is exactly what renders.
 */`,
  `export interface Review {
  /** Reviewer name as shown. */
  n: string;
  /** The review body. Rendered inside typographic quotes by the card. */
  q: string;
}

export const REVIEWS: readonly Review[] = ${lit(REVIEWS.map(({ n, q }) => ({ n, q })))};`,
);

write(
  'projects.ts',
  `${GEN('assets/site.js:2019 — PROJECTS')}

/**
 * The eight gallery projects. \`gallery\` entries are [url, width, height] —
 * the intrinsic dimensions matter because the lightbox sizes its stage from
 * the aspect ratio before the image has loaded.
 */`,
  `export interface Project {
  key: string;
  name: string;
  place: string;
  /** Display URL for the door/tile; look it up in SRCSET. */
  img: string;
  brand: boolean;
  /** Shown in the detail view's meta row; omitted when empty. */
  type: string;
  /** "What we did" paragraph. Empty on projects with no write-up yet. */
  story: string;
  /** Name of the REVIEWS entry to pull into the detail view, when there is one. */
  reviewBy?: string;
  gallery: readonly (readonly [string, number, number])[];
}

export const PROJECTS: readonly Project[] = ${lit(PROJECTS)};`,
);

write(
  'faqs.ts',
  `${GEN('assets/site.js:2539 — FAQS')}

/**
 * Twelve questions in four groups. The index down the left renders \`label\`
 * (the short form) with \`q\` behind it for the selected state; the plate shows
 * \`tag\`, \`q\` and \`a\`. Group order is the array's own order — the builder
 * starts a new group whenever \`g\` changes, so the array must stay sorted by
 * group, and it is.
 */`,
  `export interface Faq {
  /** Group heading in the index. */
  g: string;
  /** Short label in the index. */
  label: string;
  /** Eyebrow above the question in the plate. */
  tag: string;
  q: string;
  a: string;
}

export const FAQS: readonly Faq[] = ${lit(FAQS)};

/** site.js:2606 — a new group starts wherever \`g\` changes, never re-sorted. */
export function faqGroups(items: readonly Faq[] = FAQS): { name: string; items: number[] }[] {
  const groups: { name: string; items: number[] }[] = [];
  items.forEach((f, i) => {
    let g = groups[groups.length - 1];
    if (!g || g.name !== f.g) {
      g = { name: f.g, items: [] };
      groups.push(g);
    }
    g.items.push(i);
  });
  return groups;
}`,
);

console.log(
  `extract-home-data: ${SERVICES.length} services, ${PROCESS.length} steps, ` +
    `${REVIEWS.length} reviews, ${PROJECTS.length} projects, ${FAQS.length} faqs`,
);
