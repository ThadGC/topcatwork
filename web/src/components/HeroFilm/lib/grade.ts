/**
 * HERO FILM — the brightness of the footage, sampled OFFLINE.
 *
 * ⛔ WHY THIS FILE EXISTS, AND WHY IT MUST NOT BECOME CODE AGAIN.
 *
 * The nav bar and the story lines each sit on a scrim whose strength is the
 * brightness of the film underneath them. Over a black quarry they need
 * nothing; over a white slab in full sun they need everything. Get it wrong in
 * either direction and the client notices — he rejected a build whose nav was
 * a flat dark bar with the note that it "has a dark navball where it is not
 * supposed to have".
 *
 * The old build computed this at runtime: it drew the <video> into a 48x8
 * canvas and called getImageData() on every animation frame. On a phone the
 * decoded frame belongs to another process, so that readback is a
 * cross-process surface acquire plus a colour conversion, measured at ~8.3ms
 * against a 16.7ms frame budget — and it ran two or three times per tick, once
 * for the nav and once per visible line. It is the most expensive thing that
 * loop did, and a colleague's build that did NOT shake was distinguished
 * precisely by having dropped it.
 *
 * But the answer never depended on the visitor. It depends on the FILM, which
 * is fixed at build time. So it is sampled once, here, by
 * scripts/grade-film.mjs, and shipped as numbers. Runtime cost: one array
 * index.
 *
 * ── how it was sampled ──────────────────────────────────────────────────────
 * Each entry is one film frame at 12fps, so index === filmSeconds * 12.
 * Values are 0..100 (divide by 100). The rules are the old build's, verbatim:
 *
 *   nav    48x4 = 192 samples of the band under the header, sorted, the
 *          ~97.4th percentile taken, floored at 0.20. NOT the max: one blown
 *          highlight in a corner must not darken the nav for a whole second.
 *   lines  48x8 = 384 samples over the line's own box, the MAX taken, no
 *          floor. A line only needs a scrim where it would otherwise sit on a
 *          bright patch, and zero is a legitimate answer.
 *
 * Both ramp luma 30 -> 185 onto 0 -> 1.
 *
 * ⚠️ RE-RUN scripts/grade-film.mjs IF THE FILM IS RE-ENCODED OR RE-CUT. The
 * tables are keyed to the frames, and a re-cut moves every one of them.
 */

export interface GradeTable {
  nav: readonly number[];
  reveal: readonly number[];
  kit: readonly number[];
}

