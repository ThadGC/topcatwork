/** Read a table at a fractional frame index, clamped and interpolated. */
export function gradeAt(table: readonly number[], frame: number): number {
  const n = table.length - 1;
  if (!(frame > 0)) return table[0] / 100;
  if (frame >= n) return table[n] / 100;
  const i = Math.floor(frame);
  const a = table[i];
  const b = table[i + 1];
  return (a + (b - a) * (frame - i)) / 100;
}
